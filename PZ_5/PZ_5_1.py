# Найти сумму чисел ряда 1, 2, 3, ..., 60 с использованием функции
# нахождения суммы. Использовать локальные переменные.


def count_c(n):
    """Вернуть сумму чисел ряда от 1 до n."""
    count = 0  # локальная переменная для суммы
    a = 1  # локальная переменная для текущего числа ряда
    while a <= n:
        count += a
        a += 1
    return count


print(count_c(60))
