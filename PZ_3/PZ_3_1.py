#Даны два целых числа: A, B. Проверить истинность высказывания:
#Справедливы неравенства A > 2 и B < 3

#Ввод чисел A и B. Если введено не целое число
#программа сообщает об ошибке и просит ввести значение заново
while True:
    try:
        a = int(input("Введите целое число A: "))
        break
    except ValueError:
        print("Ошибка: необходимо ввести целое число.")

while True:
    try:
        b = int(input("Введите целое число B: "))
        break
    except ValueError:
        print("Ошибка: необходимо ввести целое число.")

#высказывание истинно, только если оба неравенства выполняются одновременно
result = a > 2 and b < 3
print("Высказывание «A > 2 и B < 3»:", result)
