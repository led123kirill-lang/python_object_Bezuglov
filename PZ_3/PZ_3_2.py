#Спектр видимого излучения представлен в таблице. Составить программу
#определяющую название цвета в зависимости от введённой длины волны:
#Цвет            Диапазон длин волн, нм
#Фиолетовый      <= 450
#Синий           450 - 480
#сине-зелёный    480 - 510
#Зелёный         510 - 550
#Жёлто-зелёный   550 - 570
#Жёлтый          570 - 590
#Оранжевый       590 - 630
#Красный         >= 630

#Ввод длины волны, значение должно быть положительным числом
#иначе программа сообщает об ошибке и просит ввести его заново
while True:
    try:
        wavelength = float(input("Введите длину волны (нм): "))
        if wavelength <= 0:
            print("Ошибка: длина волны должна быть больше нуля.")
            continue
        break
    except ValueError:
        print("Ошибка: необходимо ввести число.")

#определение цвета: диапазоны проверяются по возрастанию
#поэтому в каждом условии достаточно указать только верхнюю границу
if wavelength <= 450:
    color = "Фиолетовый"
elif wavelength <= 480:
    color = "Синий"
elif wavelength <= 510:
    color = "Сине-зелёный"
elif wavelength <= 550:
    color = "Зелёный"
elif wavelength <= 570:
    color = "Жёлто-зелёный"
elif wavelength <= 590:
    color = "Жёлтый"
elif wavelength < 630:
    color = "Оранжевый"
else:
    color = "Красный"

print("Цвет:", color)
