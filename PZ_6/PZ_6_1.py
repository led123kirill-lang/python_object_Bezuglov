#дан первый члун А и знаменатель D геометрической прогрессии.
#Вывести спосок размера 10 и вывести геометрическую прогрессию (A * D, A * D ** 2, A * D ** 3 .....) размером 10
A = int(input("Введите 1 число"))
D = int(input("Введите 2 число"))
B = []
for i in range(0, 10):
    B.append(A * D ** i)
print(B)