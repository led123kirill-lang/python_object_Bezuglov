#Дано вещественное число — цена 1 кг конфет
#Вывести стоимость 0.1, 0.2, ..., 1 кг конфет
#ввод цены, значение должно быть неотрицательным числом,
#иначе программа сообщает об ошибке и просит ввести его заново
while True:
    try:
        a = float(input("Введите цену 1 кг конфет: "))
        if a < 0:
            print("Ошибка: цена не может быть отрицательной.")
            continue
        break
    except ValueError:
        print("Ошибка: необходимо ввести число.")

# вес считается через целый счётчик (вес = i / 10)
# чтобы избежать накопления ошибки при сложении 0.1
i = 1
while i <= 10:
    w = i / 10
    print(f"Стоимость {w:.1f} кг: {a * w:.2f}")
    i += 1
