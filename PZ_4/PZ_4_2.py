#Дано целое число N (> 0). Используя операции деления нацело
#и взятия остатка от деления, найти число, полученное
#при прочтении числа N справа налево.

#Ввод числа N, значение должно быть целым и больше нуля,
#иначе программа сообщает об ошибке и просит ввести его заново
while True:
    try:
        n = int(input("Введите целое число N (> 0): "))
        if n <= 0:
            print("Ошибка: число должно быть больше нуля.")
            continue
        break
    except ValueError:
        print("Ошибка: необходимо ввести целое число.")

#на каждом шаге берётся последняя цифра n % 10
#и дописывается в конец перевёрнутого числа
revers = 0
while n > 0:
    revers = revers * 10 + n % 10
    n //= 10

print("Число, прочитанное справа налево:", revers)
