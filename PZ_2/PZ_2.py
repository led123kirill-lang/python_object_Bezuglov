# Программа определяет расстояние между двумя автомобилями через T часов
# Автомобили уезжают друг от друга, поэтому их скорости складываются

while True:
    try:
        v1 = int(input("Введите скорость первого автомобиля: "))
        v2 = int(input("Введите скорость второго автомобиля: "))
        s = int(input("Введите начальное расстояние: "))
        t = int(input("Введите время: "))
    except ValueError:
        # Если пользователь ввёл не число — просим ввести заново
        print("Ошибка: необходимо вводить числа. Попробуйте ещё раз.")
        continue

    ds = s + (v1 + v2) * t
    print("Расстояние между автомобилями:", ds, "км")
    break
