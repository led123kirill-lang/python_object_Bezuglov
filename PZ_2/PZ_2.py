#Программа определяетрасстояние между двумя автомбилями через Т часов.
#Сначала вводятся скорости, время и растоянние.
#Потом вычисляется расстояние прейденное обоими автомобилями.
#В конце программа выводи полученное растояние.
V1 = int(input("Введите скорость первого автомобиля:"))
V2 = int(input("Введите скорость ворого автомобиля:"))
S = int(input("Введите начальное растояние:"))
T = int(input("Введите время:"))
DT = S + (V1 + V2) * T
print("Расстояние между автомобилями:",DT,"км")